//! Generate `src/prior.rs` from the corpus files: order-1 transition
//! counts with Witten–Bell style back-off to order 0, scaled so each
//! context row totals about 1024 and every alphabet symbol keeps ≥ 1.

use std::fmt::Write as _;
use std::path::PathBuf;

use fika_proto::text::{ALPHABET, SYM_EOT, SYM_ESC, symbol_of};

const ROW_TOTAL: u32 = 1024;
const BACKOFF_K: f64 = 24.0;

#[allow(clippy::needless_range_loop)]
fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let mut lines: Vec<String> = Vec::new();
    for name in ["en.txt", "sv.txt"] {
        let text = std::fs::read_to_string(root.join("corpus").join(name)).expect("corpus file");
        lines.extend(
            text.lines()
                .filter(|l| !l.trim().is_empty())
                .map(str::to_string),
        );
    }
    let mut counts = vec![[0u64; ALPHABET]; ALPHABET];
    let mut order0 = [0u64; ALPHABET];
    for line in &lines {
        let mut ctx = SYM_EOT;
        let syms = line
            .chars()
            .map(|c| symbol_of(c).unwrap_or(SYM_ESC))
            .chain(std::iter::once(SYM_EOT));
        for s in syms {
            counts[ctx][s] += 1;
            order0[s] += 1;
            ctx = s;
        }
    }
    let total0: f64 = order0.iter().sum::<u64>() as f64;
    let p0: Vec<f64> = order0
        .iter()
        .map(|&c| (c as f64 + 0.5) / (total0 + 0.5 * ALPHABET as f64))
        .collect();

    let mut out = String::new();
    writeln!(
        out,
        "//! Static order-1 prior for the text model. GENERATED by"
    )
    .unwrap();
    writeln!(
        out,
        "//! `cargo run -p fika-proto --bin train_prior`; do not edit."
    )
    .unwrap();
    writeln!(
        out,
        "//! Corpus: {} lines. Any change here is a protocol change.\n",
        lines.len()
    )
    .unwrap();
    writeln!(out, "pub static PRIOR: [[u16; {ALPHABET}]; {ALPHABET}] = [").unwrap();
    for ctx in 0..ALPHABET {
        let row_total: f64 = counts[ctx].iter().sum::<u64>() as f64;
        let lambda = row_total / (row_total + BACKOFF_K);
        let budget = (ROW_TOTAL - ALPHABET as u32) as f64;
        write!(out, "    [").unwrap();
        for s in 0..ALPHABET {
            let p1 = if row_total > 0.0 {
                counts[ctx][s] as f64 / row_total
            } else {
                0.0
            };
            let p = lambda * p1 + (1.0 - lambda) * p0[s];
            let f = 1 + (p * budget).round() as u16;
            write!(out, "{f},").unwrap();
        }
        writeln!(out, "],").unwrap();
    }
    writeln!(out, "];").unwrap();
    let path = root.join("src").join("prior.rs");
    std::fs::write(&path, out).expect("write prior.rs");
    eprintln!("wrote {} from {} lines", path.display(), lines.len());
}
